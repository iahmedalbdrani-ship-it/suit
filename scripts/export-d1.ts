/**
 * Generates the Cloudflare D1 files from the app's own schema + seed code:
 *   migrations/0001_schema.sql   (always)
 *   db/seed.sql                  (admin account from ADMIN_EMAIL/ADMIN_PASSWORD, cities, and demo data when SEED_DEMO_DATA != false)
 * Usage: npm run d1:export
 */
import { mkdtempSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { DatabaseSync } from "node:sqlite";

const dir = mkdtempSync(join(tmpdir(), "suitly-export-"));
process.env.DATABASE_PATH = join(dir, "export.db");

async function main() {
  const { SCHEMA } = await import("../lib/db/schema");
  mkdirSync("migrations", { recursive: true });
  mkdirSync("db", { recursive: true });
  writeFileSync("migrations/0001_schema.sql", SCHEMA.trim() + "\n");

  const { localBackend } = await import("../lib/db/local");
  const { bootstrap } = await import("../lib/db/bootstrap");
  const { db } = await import("../lib/db");
  await db().prepare("SELECT 1").get(); // opens the local backend and runs bootstrap()
  void localBackend; void bootstrap;

  const conn = new DatabaseSync(process.env.DATABASE_PATH!);
  const q = (v: unknown): string => {
    if (v === null || v === undefined) return "NULL";
    if (typeof v === "number" || typeof v === "bigint") return String(v);
    return `'${String(v).replace(/'/g, "''")}'`;
  };
  const tables = ["users", "cities", "listings", "photos", "calendar_days", "bookings", "payments", "reviews", "messages"];
  const out: string[] = ["-- Generated by scripts/export-d1.ts — contains password hashes; do not commit."];
  for (const t of tables) {
    const rows = conn.prepare(`SELECT * FROM ${t}`).all() as Record<string, unknown>[];
    for (const r of rows) {
      const cols = Object.keys(r);
      out.push(`INSERT INTO ${t} (${cols.join(", ")}) VALUES (${cols.map((c) => q(r[c])).join(", ")});`);
    }
    console.log(`${t}: ${rows.length}`);
  }
  writeFileSync("db/seed.sql", out.join("\n") + "\n");
  conn.close();
  rmSync(dir, { recursive: true, force: true });
}
main().then(() => process.exit(0), (e) => { console.error(e); process.exit(1); });
